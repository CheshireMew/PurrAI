"""Generate administration TypeScript contracts and browser catalog from Python."""

import argparse
import json
import re
from pathlib import Path

from purrai.admin_catalog import admin_catalog

ROOT = Path(__file__).resolve().parents[1]


def typescript(schema):
    if "$ref" in schema:
        return type_name(schema["$ref"].rsplit("/", 1)[-1])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in schema["enum"])
    variants = schema.get("anyOf", schema.get("oneOf"))
    if variants:
        return " | ".join(typescript(item) for item in variants)
    if "allOf" in schema:
        return " & ".join(typescript(item) for item in schema["allOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    if kind == "object" or "properties" in schema:
        required = schema.get("required", [])
        fields = [f"{json.dumps(name)}{'' if name in required else '?'}: {typescript(value)}"
                  for name, value in schema.get("properties", {}).items()]
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            fields.append(f"[key: string]: {typescript(extra)}")
        elif extra is True:
            fields.append("[key: string]: unknown")
        return "{ " + "; ".join(fields) + " }" if fields else "Record<string, unknown>"
    return {"integer": "number", "number": "number", "boolean": "boolean", "string": "string",
            "null": "null"}.get(kind, "unknown")


def type_name(name):
    return re.sub(r"\W", "_", name)


def administration_types():
    # Installing the routes builds their schema without starting the application,
    # opening a database, or loading credentials from .env.
    from fastapi import FastAPI
    from purrai.api import install_api

    app = FastAPI()
    install_api(app)
    document = app.openapi()
    lines = ["// Generated by scripts/sync_admin_contract.py; edit Python API models.",
             "// Response validation and these types use the same OpenAPI contract.",
             "import type { GroupSettings } from './groupSettings'",
             "export type { GroupSettings } from './groupSettings'", ""]
    for name, schema in sorted(document["components"]["schemas"].items()):
        if name == "GroupSettings":
            continue
        if name == "JsonValue":
            lines.append("export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue }")
            continue
        lines.append(f"export type {type_name(name)} = {typescript(schema)}")
    lines.extend(["", "export interface AdminEndpoints {"])
    for path, operations in sorted(document["paths"].items()):
        for method, operation in sorted(operations.items()):
            response = operation["responses"]["200"].get("content", {})
            media = response.get("application/json") or response.get("application/x-ndjson")
            if not media or not media.get("schema"):
                raise ValueError(f"Missing response contract: {method} {path}")
            body = operation.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            request = typescript(body) if body else "never"
            lines.append(f'  "{method.upper()} {path}": {{ response: {typescript(media["schema"])}; body: {request} }}')
    return "\n".join(lines + ["}", ""])


def settings_type(fields):
    lines = [
        "// Generated by scripts/sync_admin_contract.py; edit GroupSettings in schemas.py.",
        "export interface GroupSettings {",
    ]
    types = {"boolean": "boolean", "integer": "number", "number": "number", "string": "string"}
    for name, field in fields.items():
        if "enum" in field:
            value = " | ".join(json.dumps(item, ensure_ascii=False) for item in field["enum"])
        elif field["type"] == "array":
            value = types[field["items"]["type"]] + "[]"
        else:
            value = types[field["type"]]
        lines.append(f"  {name}: {value}")
    return "\n".join(lines + ["}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = admin_catalog()
    outputs = {
        ROOT / "frontend/src/adminApi.ts": administration_types(),
        ROOT / "frontend/src/groupSettings.ts": settings_type(catalog["settings"]["fields"]),
        ROOT / "frontend/e2e/fixtures/catalog.json": json.dumps(catalog, ensure_ascii=False, indent=2) + "\n",
    }
    stale = []
    for path, content in outputs.items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        elif not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(str(path.relative_to(ROOT)))
    if stale:
        parser.exit(1, "配置契约需要同步：" + "、".join(stale) + "；运行本脚本 --write。\n")
    print("管理配置契约已同步" if args.write else "管理配置契约一致")


if __name__ == "__main__":
    main()
